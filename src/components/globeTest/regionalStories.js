// Author-supplied scripts. Do not trim text: leading spaces and punctuation
// belong to the dialogue. Draft topics are stored but have no public entry.
const topic = (group, id, title, script = '', status = 'complete') => ({
  group, id: `${group}-${id}`, title, status, background: null,
  dialogue: script ? script.split('\n').flatMap((line, index) => {
    const separator = line.indexOf('：')
    if (separator < 0 || !line.slice(separator + 1).trim()) return []
    return [{ id: `message-${index + 1}`, character: line.slice(0, separator), text: line.slice(separator + 1) }]
  }) : [],
})
const draft = (group, id, title, script = '') => topic(group, id, title, script, 'draft')

